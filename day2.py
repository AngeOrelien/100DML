"""
    ------------------------------------------------------------------------------------------------------------
    100DML - Day 2: Les algorithmes de Machine Learning
    ------------------------------------------------------------------------------------------------------------
    
    Les algorithmes de Machine Learning sont des méthodes mathématiques et statistiques 
    utilisées pour permettre aux ordinateurs d'apprendre à partir de données. Ils sont 
    essentiels pour le développement de modèles de Machine Learning efficaces.
    
    Voici quelques-uns des algorithmes de Machine Learning les plus couramment utilisés :
    
    - Régression linéaire : un algorithme d'apprentissage supervisé utilisé pour prédire une variable continue 
        à partir d'une ou plusieurs variables indépendantes. 
        Exemple : prédire le prix d'une maison en fonction de sa superficie, du nombre de chambres, etc.
        
    - Régression logistique : un algorithme d'apprentissage supervisé utilisé pour prédire une variable binaire 
        à partir d'une ou plusieurs variables indépendantes. 
        Exemple : prédire si un email est un spam ou non en fonction de son contenu.
        
    - Arbres de décision : un algorithme d'apprentissage supervisé qui utilise une structure arborescente pour 
        prendre des décisions basées sur les caractéristiques des données. 
        Exemple : un arbre de décision pour classer les types de fleurs en fonction de leurs caractéristiques
    
    - Forêts aléatoires : un algorithme d'apprentissage supervisé qui combine plusieurs arbres de décision 
        pour améliorer la précision et réduire le risque de surapprentissage. 
        Exemple : une forêt aléatoire pour prédire les maladies en fonction des symptômes des patients
        
    - K-means : un algorithme d'apprentissage non supervisé utilisé pour regrouper des données en k clusters 
        basés sur leurs caractéristiques. 
        Exemple : un algorithme K-means pour segmenter les clients en fonction de leurs comportements d'achat.
        
    - Réseaux de neurones : un algorithme d'apprentissage supervisé inspiré du fonctionnement du cerveau humain,
        utilisé pour résoudre des problèmes complexes tels que la reconnaissance d'images et le traitement du langage naturel. 
        Exemple : un réseau de neurones pour reconnaître les visages dans des photos.
        
    - Support Vector Machines (SVM) : un algorithme d'apprentissage supervisé utilisé pour la classification et la régression,
        qui trouve l'hyperplan optimal pour séparer les classes de données. 
        Exemple : un SVM pour classer les emails en spam ou non spam.
        
    - K-nearest neighbors (KNN) : un algorithme d'apprentissage supervisé utilisé pour la classification et la régression,
        qui classe les données en fonction de la proximité de leurs voisins les plus proches. 
        Exemple : un KNN pour recommander des produits en fonction des achats précédents des clients
        
    Il est important de choisir l'algorithme de Machine Learning approprié en fonction du type de données, du problème à 
    résoudre et des objectifs du projet.
    
"""